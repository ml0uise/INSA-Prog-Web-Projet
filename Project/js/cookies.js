/**
 * Defines the maximum number of highscores stored in session storage.
 */
const HIGHSCORE_LIMIT = 10;  // Number of highscores to keep


/**
 * Represents a player entry in the highscore table.
 * Each instance stores a player name and an associated score.
 */
class Player {
    constructor (name, score) {
        this.name = name;
        this.score = score;
    }
}


/**
 * Retrieves the score of a given user from session storage.
 *
 * @param {string} user - The user identifier (e.g. "Player 1")
 * @returns {number|string} The stored score, or a sentinel value if missing
 */
function get_score_session(user) {
    let score = sessionStorage.getItem(`${user} score`);

    // Returns a sentinel value when no score is found
    if (score === null) {
        return -42
    } else {
        return score;
    }
}

/**
 * Stores the score of a given user in session storage.
 *
 * @param {string} user - The user identifier
 * @param {number} score - The score to store
 */
function set_score_session(user, score) {
    sessionStorage.setItem(`${user} score`, String(score));
}


/**
 * Retrieves the display name of a user from session storage.
 * If no name exists, the name change workflow is triggered.
 *
 * @param {string} user - The user identifier
 * @returns {string} The resolved username
 */
function get_name(user) {
    let name = sessionStorage.getItem(user);

    if (name === null) {
        return change_name(user);
    } else {
        return name;
    }
}

/**
 * Prompts the user to enter or update their display name.
 * The name is sanitized, length-limited, and persisted in session storage.
 *
 * @param {string} user - The user identifier
 * @returns {string} The validated username
 */
function change_name(user) {
    let old_name = sessionStorage.getItem(user);
    let def;

    // Determines the default value shown in the prompt
    if (old_name === null) {
        def = user;
    } else {
        def = old_name;
    }

    let name = prompt(`${user}, enter your username (max 12 characters):`, def);

    // Falls back to the default identifier if input is cancelled or empty
    if (name === null || name.trim() === "") {
        name = user;
    }

    // Enforces maximum length and trims whitespace
    name = name.trim().substring(0, 12);

    // Persists the username in session storage
    sessionStorage.setItem(user, name);

    return name;
}


/**
 * Retrieves the list of stored highscores from session storage.
 * The list is expected to be ordered by score in descending order.
 *
 * @returns {Array<Player>} An array of Player objects
 */
function get_highscores() {
    // Example structure: [Player1, Player2, ...]
    // Ordered by score (descending)

    let scores = sessionStorage.getItem("highscores");

    if (scores === null) {
        return [];
    } else {
        return JSON.parse(scores);
    }
}

/**
 * Inserts a new score into the highscore list and persists the updated list.
 * The list is sorted and truncated to the configured maximum size.
 *
 * @param {string} user - The user identifier
 * @param {number} score - The score to record
 */
function update_highscores(user, score) {
    let actual = get_highscores();
    let player = new Player(get_name(user), score);

    // Adds the new player entry
    actual.push(player);

    // Sorts highscores in descending order
    actual.sort(function (a, b) {return b.score - a.score});  // Sort new highscore

    // Intended to limit the list to the maximum allowed size
    actual.slice(HIGHSCORE_LIMIT);  // Only keep a few highscores
    
    // Persists the updated highscore list
    sessionStorage.setItem("highscores", JSON.stringify(actual));
}


/**
 * Marks the game state as active and returns the previous state.
 * This mechanism prevents duplicate game-over logic execution.
 *
 * @returns {boolean|undefined} The previous game state if defined
 */
function increment_game_state() {
    let gameState = sessionStorage.getItem("game_state");

    // Sets the current game state as active
    sessionStorage.setItem("game_state", "true");

    if (gameState === "true") return true;
    else if (gameState === "false") return false;
}

/**
 * Resets the game state flag in session storage.
 * This function is typically called when the game is fully released or reset.
 */
function release_game_state() {
    sessionStorage.setItem("game_state", "false");
}
